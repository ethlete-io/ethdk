import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const partPath = '.ethlete/design/studio/foundations/colors/colors.css';
const themesPath = 'apps/ethlete-studio/src/themes.ts';
const surfaceThemesPath = 'apps/ethlete-studio/src/surface-themes.ts';
const check = process.argv.includes('--check');

const tokens = new Map(
  [...readFileSync(join(root, partPath), 'utf8').matchAll(/^\s*--([\w-]+):\s*oklch\(([^)]*)\);/gm)].map(
    ([, name, value]) => [name, value.split(/[\s/]+/).map(Number)],
  ),
);

const oklab = (name) => {
  const value = tokens.get(name);
  if (!value) throw new Error(`${partPath} has no oklch token --${name}`);
  const [l, c, h] = value;
  const rad = (h * Math.PI) / 180;
  return [l, c * Math.cos(rad), c * Math.sin(rad)];
};

const mix = (from, to, amount) => from.map((value, index) => value * amount + to[index] * (1 - amount));

const channels = ([l, a, b]) => {
  const lms = [
    l + 0.3963377774 * a + 0.2158037573 * b,
    l - 0.1055613458 * a - 0.0638541728 * b,
    l - 0.0894841775 * a - 1.291485548 * b,
  ].map((value) => value ** 3);
  const linear = [
    4.0767416621 * lms[0] - 3.3077115913 * lms[1] + 0.2309699292 * lms[2],
    -1.2684380046 * lms[0] + 2.6097574011 * lms[1] - 0.3413193965 * lms[2],
    -0.0041960863 * lms[0] - 0.7034186147 * lms[1] + 1.707614701 * lms[2],
  ];
  return linear
    .map((value) => (value <= 0.0031308 ? 12.92 * value : 1.055 * value ** (1 / 2.4) - 0.055))
    .map((value) => Math.round(Math.min(1, Math.max(0, value)) * 255))
    .join(' ');
};

const rgb = (name) => channels(oklab(name));
const faded = (name, amount) => channels(mix(oklab(name), oklab('surface'), amount));

const colorTheme = (token, extra) => ({
  ...extra,
  primary: {
    color: {
      default: rgb(token),
      hover: rgb(`${token}-hover`),
      focus: rgb(token === 'accent' ? 'focus-ring' : `${token}-hover`),
      active: rgb(token),
      disabled: faded(token, 0.4),
    },
    onColor: { default: rgb(`on-${token}`), disabled: faded(`on-${token}`, 0.6) },
    inkColor: {
      default: rgb(`${token}-text`),
      hover: rgb(`${token}-text`),
      focus: rgb(`${token}-text`),
      active: rgb(`${token}-text`),
      disabled: faded(`${token}-text`, 0.4),
    },
  },
});

const surfaceTheme = (name, elevation, background) => ({
  name,
  type: 'dark',
  elevation,
  ...(elevation === 0 ? { isDefault: true } : {}),
  interactionColor: 'DARK_INTERACTION',
  background: rgb(background),
  color: rgb('text'),
  colorMuted: rgb('text-muted'),
  colorSubtle: rgb('text-muted'),
  border: rgb('surface-border'),
});

const literal = (value) => JSON.stringify(value, null, 2).replace(/"DARK_INTERACTION"/, 'DARK_INTERACTION');
const header = `// Generated by tools/scripts/generate-studio-themes.mjs from ${partPath}. Do not edit; run \`yarn studio:themes\`.\n`;

const colorThemes = {
  BRAND_THEME: colorTheme('accent', { name: 'brand', isDefault: true }),
  DANGER_THEME: colorTheme('danger', { name: 'danger', type: 'error' }),
  WARNING_THEME: colorTheme('warning', { name: 'warning', type: 'warning' }),
};

const surfaceThemes = {
  DARK_SURFACE: surfaceTheme('dark', 0, 'surface'),
  DARK_ELEVATED_SURFACE: surfaceTheme('dark-elevated', 1, 'surface-raised'),
  DARK_ELEVATED_2_SURFACE: surfaceTheme('dark-elevated-2', 2, 'surface-overlay'),
};

const files = {
  [themesPath]: `${header}import { ColorTheme } from '@ethlete/core';

${Object.entries(colorThemes)
  .map(([name, theme]) => `export const ${name}: ColorTheme = ${literal(theme)};`)
  .join('\n\n')}

export const THEMES = [${Object.keys(colorThemes).join(', ')}];
`,
  [surfaceThemesPath]: `${header}import { SurfaceInteractionColor, SurfaceTheme } from '@ethlete/core';

const DARK_INTERACTION: SurfaceInteractionColor = ${literal({
    color: {
      default: rgb('text-muted'),
      hover: rgb('text'),
      focus: rgb('text'),
      active: rgb('text'),
      disabled: rgb('surface-border'),
    },
  })};

${Object.entries(surfaceThemes)
  .map(([name, theme]) => `export const ${name}: SurfaceTheme = ${literal(theme)};`)
  .join('\n\n')}

export const SURFACE_THEMES = [${Object.keys(surfaceThemes).join(', ')}];
`,
};

const stale = [];

for (const [path, source] of Object.entries(files)) {
  const file = join(root, path);
  const formatted = await format(source, { ...(await resolveConfig(file)), filepath: file });
  if (readFileSync(file, 'utf8') === formatted) continue;
  stale.push(path);
  if (!check) writeFileSync(file, formatted);
}

if (check) {
  if (stale.length) {
    console.error(`Stale, run \`yarn studio:themes\`: ${stale.join(', ')}`);
    process.exit(1);
  }
  process.exit(0);
}

for (const [generator, themes, output] of [
  ['tailwind-4-color-theme', themesPath, 'apps/ethlete-studio/src/styles/themes.css'],
  ['tailwind-4-surface-theme', surfaceThemesPath, 'apps/ethlete-studio/src/styles/surface-themes.css'],
]) {
  execFileSync(
    'npx',
    [
      'nx',
      'g',
      `./libs/core/generators/generators.json:${generator}`,
      `--themesPath=${themes}`,
      `--outputPath=${output}`,
    ],
    { cwd: root, stdio: 'inherit', env: { ...process.env, NX_NO_CLOUD: 'true' } },
  );
}
