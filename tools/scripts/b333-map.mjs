import fs from 'node:fs';
const items = (t, from, to) => t.split('\n').map((l, i) => [i, l]).filter(([i, l]) => i >= from && i < to && /^\d+\. /.test(l)).map(([i, l]) => ({ i, n: +l.match(/^(\d+)\./)[1], key: l.replace(/^\d+\. /, '').slice(0, 50) }));
const old = fs.readFileSync('/tmp/b333-old.md', 'utf8');
const oldItems = items(old, 561, 4680);
const byKey = new Map(oldItems.map((x) => [x.key, x.n]));
const arch = items(fs.readFileSync(process.argv[2], 'utf8'), 0, 1e9);
console.log('archive mismatches', arch.filter((x) => byKey.get(x.key) !== x.n).map((x) => [x.n, byKey.get(x.key)]));
const curT = fs.readFileSync(process.argv[3], 'utf8');
