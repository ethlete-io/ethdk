const fixtureDir = fs.mkdtempSync(path.join(os.tmpdir(), 'no-old-theme-token-'));
afterAll(() => fs.rmSync(fixtureDir, { recursive: true, force: true }));

const writeTheme = (name, kind, prefix, names) => {
  const file = path.join(fixtureDir, name);
  const body = names
    .map((n) => `  /* ${n} ${kind === 'color' ? 'theme' : 'surface'} */\n  .${prefix}-${kind}--${n} {}`)
    .join('\n');
  fs.writeFileSync(
    file,
    `/*\n * Auto-generated by @ethlete/core:tailwind-4-${kind}-theme\n * nx g ... --prefix=${prefix}\n */\n${body}\n`,
  );
  return path.relative(process.cwd(), file);
};

