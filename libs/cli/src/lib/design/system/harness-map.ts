import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, relative, resolve, sep } from 'path';
import { DesignHarness } from '../paths';
import { harnessProblemOf } from './harness-config';
import { formattedTextOf } from './prettier';
import { partKeyOf, ResolvedProduct } from './resolve-product';
import { partLinkOf } from './sketch/part-definition';
import { exportedComponentClassesOf } from './ts-source';

export type HarnessEntry = { part: string; specifier: string; component: string };

/** The `harness` a product declares in config.json, `null` without one, or why it is unusable. */
export const harnessOf = (product: ResolvedProduct): DesignHarness | null | string => {
  const harness = product.config.harness;

  if (harness === undefined) return null;

  const problem = harnessProblemOf(harness);

  return problem === null ? harness : `product "${product.name}": ${problem}`;
};

const specifierOf = (options: { map: string; component: string }) => {
  const path = relative(dirname(options.map), options.component).split(sep).join('/').replace(/\.ts$/, '');

  return path.startsWith('.') ? path : `./${path}`;
};

/** One entry per part whose `implements` names a component, sorted by part; a route-only link has none. */
export const harnessEntriesOf = (options: {
  target: string;
  product: ResolvedProduct;
  map: string;
}): HarnessEntry[] | string => {
  const { target, product, map } = options;
  const entries: HarnessEntry[] = [];
  const errors: string[] = [];

  for (const part of product.parts) {
    const key = partKeyOf(part);
    const link = partLinkOf(part.source);

    if (link.kind === 'unreadable') {
      errors.push(`${key} has an implements link that is not a literal`);
      continue;
    }

    const path = link.kind === 'component' ? link.path : link.kind === 'route' ? link.component : null;

    if (path === null) continue;

    const file = resolve(target, path);

    if (!existsSync(file)) {
      errors.push(`${key} implements ${path}, which does not exist`);
      continue;
    }

    const classes = exportedComponentClassesOf(readFileSync(file, 'utf8'));

    if (classes.length !== 1) {
      errors.push(
        `${key} implements ${path}, which exports ${classes.length === 0 ? 'no' : classes.length} @Component classes - it needs exactly one`,
      );
      continue;
    }

    entries.push({
      part: key,
      specifier: specifierOf({ map: resolve(target, map), component: file }),
      component: classes[0] ?? '',
    });
  }

  if (errors.length > 0) return errors.join('\n');

  return entries.sort((a, b) => (a.part < b.part ? -1 : a.part > b.part ? 1 : 0));
};

/** The unformatted source of a harness map. */
export const harnessMapSourceOf = (options: { product: string; entries: HarnessEntry[] }) =>
  [
    `// Generated by \`et design harness --product ${options.product}\` from the parts' implements links. Do not edit.`,
    `import { Type } from '@angular/core';`,
    ``,
    `export const DESIGN_HARNESS_PARTS: Record<string, () => Promise<Type<unknown>>> = {`,
    ...options.entries.map(
      (entry) => `  '${entry.part}': () => import('${entry.specifier}').then((m) => m.${entry.component}),`,
    ),
    `};`,
    ``,
  ].join('\n');

export type HarnessMap = { file: string; text: string; current: boolean };

/** The formatted harness map of a product, where it goes, and whether the file on disk already holds it. */
export const harnessMapOf = (options: { target: string; product: ResolvedProduct }): HarnessMap | null | string => {
  const { target, product } = options;
  const harness = harnessOf(product);

  if (harness === null || typeof harness === 'string') return harness;

  const entries = harnessEntriesOf({ target, product, map: harness.map });

  if (typeof entries === 'string') return entries;

  const file = resolve(target, harness.map);
  const text = formattedTextOf({ target, file, text: harnessMapSourceOf({ product: product.name, entries }) });

  if (typeof text !== 'string') return `cannot format ${harness.map}: ${text.error}`;

  return { file, text, current: existsSync(file) && readFileSync(file, 'utf8') === text };
};

export const writeHarnessMap = (map: HarnessMap) => {
  mkdirSync(dirname(map.file), { recursive: true });
  writeFileSync(map.file, map.text);
};

/** Why compare cannot trust the product's harness map, or `null` when it is current or the product has no harness. */
export const harnessStaleOf = (options: { target: string; product: ResolvedProduct }): string | null => {
  const map = harnessMapOf(options);

  if (map === null) return null;
  if (typeof map === 'string') return map;
  if (map.current) return null;

  return `the harness map ${relative(options.target, map.file)} is stale - run et design harness --product ${options.product.name}`;
};
